export const courses: Course[] = seeds.map((seed) => {
  const lessons = getLessons(seed.id)
  const durationMinutes = lessons.reduce((total, lesson) => total + lesson.durationMinutes, 0)
  return {
    ...seed,
    durationMinutes,
    duration: formatMinutes(durationMinutes),
    lessonsCount: lessons.length,
  }
})

export const getCourse = (id: string) => courses.find((course) => course.id === id)
export const getCoursesByCategory = (categoryId: string) =>
  courses.filter((course) => course.categoryId === categoryId)
export const getCoursesByInstructor = (instructorId: string) =>
  courses.filter((course) => course.instructorId === instructorId)
